#!/usr/bin/env sh
# Regenerate the help and version text the sandbox prints, straight from the
# compiled binary, so the playground can never drift from the real program.
# Run `cargo build --release` first; the parity tests fail when the committed
# copy and the binary disagree.
set -eu

root=$(cd "$(dirname "$0")/../.." && pwd)
binary=${MGIT_BINARY:-"$root/target/release/mgit"}
out="$root/website/assets/js/engine/help.js"

if [ ! -x "$binary" ]; then
  printf 'capture-cli: %s is not executable; run `cargo build --release` first\n' "$binary" >&2
  exit 1
fi

version=$("$binary" --version)

{
  printf '// Generated by website/build/capture-cli.sh from `mgit --help` and\n'
  printf '// `mgit --version` of the compiled binary. Do not edit by hand: the parity\n'
  printf '// tests compare this file against the real program.\n\n'
  printf 'export const VERSION = %s;\n\n' "$(printf '%s' "${version#mgit }" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))')"
  printf 'export const VERSION_TEXT = %s;\n\n' "$(printf '%s' "$version" | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))')"
  printf 'export const HELP_TEXT = %s;\n' "$("$binary" --help | python3 -c 'import json,sys; print(json.dumps(sys.stdin.read()))')"
} > "$out"

printf 'capture-cli: wrote %s from %s\n' "$out" "$binary"
